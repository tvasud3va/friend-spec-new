"""Load and validate friend.toml and the generated plan. Every path the harness uses comes from here."""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import tomllib
from dataclasses import dataclass
from pathlib import Path


HARNESS = Path(__file__).resolve().parent
KIT = HARNESS / "testkit"


def rel_or_abs(root: Path, p: Path) -> str:
    """Path relative to the project root when inside it, else absolute."""
    try:
        return str(p.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(p.resolve())


class ConfigError(Exception):
    pass


DEFAULTS = {
    "layout": {"spec": "spec", "generated": "clients", "tests": "tests/generated", "plan": "plan.json",
               "approvals": "approvals.json", "holdout": []},
    "agent": {"command": "claude", "model": "", "effort": "", "max_budget_usd": 20.0, "step_timeout_s": 2400,
              "agent_retries": 1},
    "workflow": {"max_test_rounds": 3, "auto_approve": False},
    "toolchain": {},
    "services": {},
}
NAME_RE = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")


@dataclass
class Config:
    root: Path
    raw: dict

    def __getitem__(self, k: str) -> dict:
        return self.raw[k]

    # layout helpers (all relative to root)
    @property
    def spec_dir(self) -> str:
        return self.raw["layout"]["spec"]

    @property
    def tests_dir(self) -> str:
        return self.raw["layout"]["tests"]

    @property
    def generated_root(self) -> str:
        return self.raw["layout"]["generated"]

    def path(self, rel: str) -> Path:
        return self.root / rel

    def runner(self) -> list[str]:
        """The test runner command, rooted at this project (the harness may live elsewhere)."""
        return ["python3", rel_or_abs(self.root, KIT / "runner.py"), "--root", "."]

    def suite_cmd(self, suite: str | None = None) -> list[str]:
        return self.runner() + ["--suite", suite or self.tests_dir]


def load(root: Path) -> Config:
    path = root / "friend.toml"
    if not path.exists():
        raise ConfigError(f"{path} not found")
    try:
        with open(path, "rb") as f:
            raw = tomllib.load(f)
    except tomllib.TOMLDecodeError as e:
        raise ConfigError(f"friend.toml: {e}")
    unknown = set(raw) - set(DEFAULTS) - {"project"}
    if unknown:
        raise ConfigError(f"friend.toml: unknown sections {sorted(unknown)}")
    for section, defaults in DEFAULTS.items():
        given = raw.get(section, {})
        if isinstance(defaults, dict) and section not in ("toolchain", "services"):
            bad = set(given) - set(defaults)
            if bad:
                raise ConfigError(f"friend.toml [{section}]: unknown keys {sorted(bad)}")
            for k, v in given.items():
                if not isinstance(v, type(defaults[k])) and not (isinstance(defaults[k], float) and isinstance(v, int)):
                    raise ConfigError(f"friend.toml [{section}].{k}: expected {type(defaults[k]).__name__}, got {v!r}")
        raw[section] = {**defaults, **given} if isinstance(defaults, dict) else given
    for name, tool in raw["toolchain"].items():
        if not isinstance(tool, dict) or not isinstance(tool.get("cmd"), str):
            raise ConfigError(f"friend.toml [toolchain.{name}]: needs cmd = \"...\"")
    for name, svc in raw["services"].items():
        if not isinstance(svc.get("launch"), list) or not isinstance(svc.get("ready"), str):
            raise ConfigError(f"friend.toml [services.{name}]: needs launch = [...] and ready = \"regex\"")
    return Config(root, raw)


# ── toolchain ─────────────────────────────────────────────────────────────────

def probe_toolchain(cfg: Config) -> tuple[dict[str, str], list[str]]:
    """Return ({tool: version string}, [problems])."""
    versions, problems = {}, []
    for name, tool in cfg["toolchain"].items():
        cmd = tool["cmd"]
        exe = str(cfg.root / cmd) if "/" in cmd else shutil.which(cmd)
        if not exe or not Path(exe).exists():
            problems.append(f"toolchain {name}: {cmd!r} not found" + (f" ({tool['install']})" if tool.get("install") else ""))
            continue
        try:
            out = subprocess.run([exe, *tool.get("version_args", ["--version"])], capture_output=True, text=True, timeout=30)
            versions[name] = (out.stdout or out.stderr).strip().splitlines()[0] if (out.stdout or out.stderr) else "?"
        except (OSError, subprocess.TimeoutExpired) as e:
            problems.append(f"toolchain {name}: {e}")
    return versions, problems


def agent_cli_version(cfg: Config) -> str | None:
    exe = shutil.which(cfg["agent"]["command"])
    if not exe:
        return None
    try:
        return subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return None


# ── plan (generated by the planner role, approved like the spec) ─────────────

def load_plan(cfg: Config) -> dict | None:
    p = cfg.path(cfg["layout"]["plan"])
    return json.loads(p.read_text()) if p.exists() else None


def validate_plan_targets(cfg: Config, targets: list[dict], platform_specs: list[str]) -> list[str]:
    """Deterministic checks on planner output. Returns problems (empty = valid)."""
    problems = []
    names = [t.get("name") for t in targets]
    if len(set(names)) != len(names):
        problems.append(f"duplicate target names: {names}")
    covered = [t.get("platform_spec") for t in targets]
    for ps in platform_specs:
        if covered.count(ps) != 1:
            problems.append(f"platform spec {ps} must map to exactly one target (found {covered.count(ps)})")
    for ps in covered:
        if ps not in platform_specs:
            problems.append(f"unknown platform spec {ps!r}")
    tools = {t["cmd"] for t in cfg["toolchain"].values()}
    for t in targets:
        n = t.get("name", "?")
        if not isinstance(n, str) or not NAME_RE.match(n):
            problems.append(f"target name {n!r} must match {NAME_RE.pattern}")
        if not t.get("comment") or len(t["comment"]) > 3 or " " in t["comment"]:
            problems.append(f"{n}: comment must be a 1-3 character line-comment token (e.g. '#', '//')")
        for key in ("launch",) + (("build",) if t.get("build") else ()):
            argv = t.get(key)
            if not isinstance(argv, list) or not argv or not all(isinstance(a, str) for a in argv):
                problems.append(f"{n}.{key} must be a non-empty list of strings")
                continue
            if argv[0] not in tools and not argv[0].startswith("{dir}/"):
                problems.append(f"{n}.{key}[0] {argv[0]!r} is not a declared toolchain command ({sorted(tools)}) or a {{dir}}/ path")
            if "{dir}" not in " ".join(argv):
                problems.append(f"{n}.{key} must reference {{dir}}")
        for cmd in t.get("selfcheck") or []:
            if not isinstance(cmd, list) or not cmd or cmd[0] not in tools:
                problems.append(f"{n}.selfcheck entries must be argv lists starting with a toolchain command: {cmd!r}")
        if not t.get("sources") or not all(isinstance(g, str) and not g.startswith("/") and ".." not in g for g in t["sources"]):
            problems.append(f"{n}.sources must be relative globs")
    return problems


def expand(argv: list[str] | None, d: str) -> list[str] | None:
    return None if argv is None else [a.replace("{dir}", d) for a in argv]
