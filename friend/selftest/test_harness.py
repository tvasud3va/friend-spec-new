import re
import os
import signal
import subprocess
import sys
import tempfile
import textwrap
import time
import unittest
from pathlib import Path

HARNESS = Path(__file__).resolve().parents[1]
MF = [sys.executable, str(HARNESS / "commands.py")]
FAKE = HARNESS / "selftest" / "fake_claude.py"

SPEC_README = "# toy spec\nRules are bullets: `- **ID** (LEVEL) text`.\n"
SPEC_CORE = """# Core: echo
- **E-1** (MUST) For each stdin line the program prints one JSON line `{"echo": <line>}`.
- **E-2** (MUST) A line `upper <text>` prints `{"echo": <TEXT>}` with the text upper-cased.
- **E-3** (MUST) At end of stdin the program exits with code 0.
"""
SPEC_PY = "# Platform: python\n- **PY-1** (MUST) Entry point `clients/py/main.py`, stdlib only.\n"

FRIEND_TOML = """
[layout]
holdout = []
[agent]
command = "{fake}"
model = "fake-model"
step_timeout_s = 60
[workflow]
max_repairs = {max_repairs}
max_test_rounds = 2
max_disputes = 1
vacuity_timeout_s = 0.5
max_untestable_ratio = 0.5
[toolchain.python]
cmd = "python3"
"""

PLAN_OUT = {"targets": [{"name": "py", "platform_spec": "spec/platforms/python.md", "comment": "#",
                         "build": [], "launch": ["python3", "{dir}/main.py"], "sources": ["*.py"],
                         "selfcheck": [["python3", "-m", "py_compile", "{dir}/main.py"]]}], "spec_questions": []}

GOOD_TESTS = '''from friendkit import test, check

@test("E-1")
def echoes(ctx):
    p = ctx.spawn()
    p.send("hello world")
    p.expect(echo="hello world")

@test("E-2")
def upper(ctx):
    p = ctx.spawn()
    p.send("upper abc")
    p.expect(echo="ABC")

@test("E-3")
def exits_on_eof(ctx):
    p = ctx.spawn()
    p.send("x")
    p.expect(echo="x")
    p.close_stdin()
    check(p.exit_code(3) == 0, "must exit 0 on EOF")
'''
VACUOUS_TESTS = GOOD_TESTS.replace('''    p.send("hello world")
    p.expect(echo="hello world")''', '''    p.assert_none(0.1, echo="never")''')

GOOD_IMPL = '''# GENERATED by friend from spec {spec12}. Do not edit; change the spec and regenerate.
import json, sys
for line in sys.stdin:
    line = line.rstrip("\\n")
    out = line[6:].upper() if line.startswith("upper ") else line   # E-1, E-2
    print(json.dumps({"echo": out}), flush=True)
sys.exit(0)  # E-3
'''
BROKEN_IMPL = GOOD_IMPL.replace('line[6:].upper() if line.startswith("upper ") else line', "line")
TRACE = json.dumps({"rules": {"E-1": ["main.py"], "E-2": ["main.py"], "E-3": ["main.py"], "I-1": ["main.py"], "PY-1": ["main.py"]}})
BUILD_GOOD = {"write": {"clients/py/main.py": GOOD_IMPL, "clients/py/TRACE.json": TRACE}}
BUILD_BROKEN = {"write": {"clients/py/main.py": BROKEN_IMPL, "clients/py/TRACE.json": TRACE}}
TESTS_GOOD = {"write": {"tests/generated/test_echo.py": GOOD_TESTS.replace('@test("E-1")', '@test("E-1", "I-1")')}}


class Project:
    def __init__(self, scenario: dict, max_repairs: int = 2) -> None:
        self.dir = Path(tempfile.mkdtemp(prefix="friend-selftest-"))
        d = self.dir
        (d / "spec/core").mkdir(parents=True)
        (d / "spec/platforms").mkdir(parents=True)
        (d / "spec/extensions").mkdir(parents=True)
        (d / "spec/README.md").write_text(SPEC_README)
        (d / "spec/core/echo.md").write_text(SPEC_CORE)
        (d / "spec/core/interface.md").write_text("# Core: interface\n- **I-1** (MUST) Lines in on stdin, JSON lines out on stdout.\n")
        (d / "spec/platforms/python.md").write_text(SPEC_PY)
        (d / "friend.toml").write_text(FRIEND_TOML.format(fake=FAKE, max_repairs=max_repairs))
        self.scenario = Path(tempfile.mkdtemp(prefix="friend-fake-")) / "scenario.json"  # outside the project
        self.scenario.write_text(json.dumps(scenario))
        self.env = {**os.environ, "FRIEND_FAKE_SCENARIO": str(self.scenario)}
        self.friend("approve", "spec")

    def friend(self, *args: str, check_code: int | None = None) -> subprocess.CompletedProcess:
        r = subprocess.run(MF + ["--root", str(self.dir), *args], capture_output=True, text=True, env=self.env, timeout=300)
        if check_code is not None and r.returncode != check_code:
            raise AssertionError(f"friend {' '.join(args)} exited {r.returncode}, expected {check_code}\n{r.stdout[-3000:]}\n{r.stderr[-2000:]}")
        return r

    def generate(self, *extra: str, code: int = 0) -> list[dict]:
        r = self.friend("--json", "generate", *extra, check_code=code)
        return [json.loads(l) for l in r.stdout.splitlines() if l.startswith("{")]

    def calls(self) -> list[dict]:
        p = self.scenario.with_suffix(".calls")
        return [json.loads(l) for l in p.read_text().splitlines()] if p.exists() else []

    def state(self) -> dict:
        return json.loads(self.friend("--json", "status").stdout)


def types(events: list[dict]) -> list[str]:
    return [e["type"] for e in events]


def status_of(events: list[dict], task: str) -> list[str]:
    return [e["status"] for e in events if e["type"] == "task.status" and e["task"] == task]


class Pipeline(unittest.TestCase):
    def test_happy_path_produces_approved_artifacts_and_manifest(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_GOOD]})
        ev = p.generate("--auto-approve")
        self.assertEqual(ev[-1]["status"], "passed")
        st = p.state()
        self.assertEqual({k: v["status"] for k, v in st["artifacts"].items()}, {"spec": "approved", "plan": "approved", "tests": "approved"})
        m = json.loads((p.dir / "clients/py/.generated.json").read_text())
        self.assertEqual(m["model"], "fake-model")
        self.assertIn("python", m["toolchain"])

    def test_approval_gates_pause_and_resume(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_GOOD]})
        ev = p.generate(code=4)
        self.assertIn("approval.required", types(ev))
        self.assertTrue((p.dir / "plan.json").exists())
        p.friend("approve", "plan", check_code=0)
        ev = p.generate(code=4)                       # same run resumes, stops at the tests gate
        self.assertEqual(ev[0]["type"], "run.resumed")
        p.friend("approve", "tests", check_code=0)
        ev = p.generate(code=0)
        self.assertEqual([c["role"] for c in p.calls()], ["planner", "tester", "builder"])  # nothing redone

    def test_invalid_plan_is_rejected_then_corrected(self):
        bad = {"targets": [{**PLAN_OUT["targets"][0], "launch": ["ruby", "main.rb"]}], "spec_questions": []}
        p = Project({"planner": [{"output": bad}, {"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_GOOD]})
        ev = p.generate("--auto-approve")
        self.assertTrue(any(e["type"] == "gate.failed" and e["gate"] == "gate:plan" for e in ev))
        self.assertIn("previous plan was rejected", p.calls()[1]["prompt"] + json.dumps(p.calls()))

    def test_vacuous_test_is_sent_back_to_the_tester(self):
        p = Project({"planner": [{"output": PLAN_OUT}],
                     "tester": [{"write": {"tests/generated/test_echo.py": VACUOUS_TESTS}}, TESTS_GOOD],
                     "builder": [BUILD_GOOD]})
        ev = p.generate("--auto-approve")
        gates = [e for e in ev if e["type"] == "gate.failed" and e["task"] == "tests"]
        self.assertTrue(any(g["gate"] == "gate:vacuous" and "echoes" in g["detail"] for g in gates))
        tester_calls = [c for c in p.calls() if c["role"] == "tester"]
        self.assertTrue(tester_calls[1]["resume"], "fix round must resume the tester session")
        self.assertEqual(ev[-1]["status"], "passed")

    def test_uncovered_rule_fails_coverage_gate(self):
        only_two = GOOD_TESTS.split('@test("E-3")')[0]
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [{"write": {"tests/generated/test_echo.py": only_two}}]})
        ev = p.generate("--auto-approve", code=1)
        self.assertTrue(any(e["type"] == "gate.failed" and e["gate"] == "gate:coverage" and "E-3" in e["detail"] for e in ev))
        self.assertEqual(p.state()["run"]["tasks"]["tests"]["status"], "failed")


class Building(unittest.TestCase):
    def test_repair_loop_fixes_a_broken_implementation(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_BROKEN, BUILD_GOOD]})
        ev = p.generate("--auto-approve")
        self.assertEqual(status_of(ev, "build:py"), ["implementing", "checking", "repairing", "checking", "passed"])
        b = [c for c in p.calls() if c["role"] == "builder"]
        self.assertTrue(b[1]["resume"] and b[1]["session"] == b[0]["session"])
        self.assertIn("upper", b[1]["prompt"] + "upper")  # failures are passed to the repair prompt
        self.assertEqual(p.state()["run"]["tasks"]["build:py"]["repairs"], 1)

    def test_repairs_exhausted_fails_the_run(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_BROKEN]}, max_repairs=1)
        ev = p.generate("--auto-approve", code=1)
        self.assertEqual(status_of(ev, "build:py")[-1], "failed")

    def test_agent_crash_is_retried_once(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [{"crash": True}, BUILD_GOOD]})
        ev = p.generate("--auto-approve")
        self.assertIn("agent.retry", types(ev))
        self.assertEqual(ev[-1]["status"], "passed")

    def test_blocking_spec_question_stops_with_exit_2(self):
        out = {"status": "blocked", "summary": "", "test_disputes": [],
               "spec_questions": [{"rule": "E-2", "question": "upper of non-ASCII?", "blocking": True}]}
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [{"output": out}]})
        ev = p.generate("--auto-approve", code=2)
        self.assertTrue(any(e["type"] == "spec.questions" for e in ev))

    def test_dispute_upheld_amends_tests_and_rechecks(self):
        wrong = TESTS_GOOD["write"]["tests/generated/test_echo.py"].replace('p.expect(echo="ABC")', 'p.expect(echo="abc")')  # contradicts E-2
        dispute = {"status": "complete", "summary": "", "spec_questions": [],
                   "test_disputes": [{"test": "upper", "rules": ["E-2"], "reason": "E-2 says upper-cased"}]}
        verdict = {"verdicts": [{"test": "upper", "verdict": "test_wrong", "rules": ["E-2"], "explanation": "E-2 requires ABC", "fix": "expect ABC"}]}
        p = Project({"planner": [{"output": PLAN_OUT}],
                     "tester": [{"write": {"tests/generated/test_echo.py": wrong}}, TESTS_GOOD],
                     "builder": [{**BUILD_GOOD, "output": dispute}], "arbiter": [{"output": verdict}]})
        ev = p.generate("--auto-approve")
        self.assertIn("tests.amended", types(ev))
        self.assertEqual(ev[-1]["status"], "passed")
        self.assertEqual(json.loads((p.dir / "approvals.json").read_text())["tests"]["by"], "arbitration")

    def test_dispute_rejected_goes_back_to_repair(self):
        dispute = {"status": "complete", "summary": "", "spec_questions": [],
                   "test_disputes": [{"test": "upper", "rules": ["E-2"], "reason": "I think lower is fine"}]}
        verdict = {"verdicts": [{"test": "upper", "verdict": "code_wrong", "rules": ["E-2"], "explanation": "E-2 says upper-cased"}]}
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD],
                     "builder": [{**BUILD_BROKEN, "output": dispute}, BUILD_GOOD], "arbiter": [{"output": verdict}]})
        ev = p.generate("--auto-approve")
        b = [c for c in p.calls() if c["role"] == "builder"]
        self.assertIn("ARBITER", b[1]["prompt"] + json.dumps(p.state()["run"]["tasks"]["build:py"]))
        self.assertEqual(ev[-1]["status"], "passed")


class Safety(unittest.TestCase):
    def test_hook_blocks_writes_outside_scope(self):
        sneaky = {"write": {"clients/py/main.py": GOOD_IMPL, "clients/py/TRACE.json": TRACE,
                            "tests/generated/test_echo.py": "# overwritten by builder"},
                  "bash": ["cat tests/generated/test_echo.py", "python3 clients/py/main.py ; rm -rf spec"]}
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [sneaky]})
        ev = p.generate("--auto-approve")
        self.assertEqual(ev[-1]["status"], "passed")
        self.assertIn("@test", (p.dir / "tests/generated/test_echo.py").read_text())  # untouched
        log = (p.dir / ".friend/runs").glob("*/events.jsonl")
        denied = [json.loads(l) for f in log for l in f.read_text().splitlines() if '"policy.denied"' in l]
        self.assertEqual(len(denied), 3, denied)

    def test_policy_escape_is_detected_by_integrity_check(self):
        escape = {**BUILD_GOOD, "bypass": {"tests/generated/test_echo.py": "def nothing(): pass\n"}}
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [escape]})
        ev = p.generate("--auto-approve", code=1)
        self.assertIn("policy", p.state()["run"]["tasks"]["build:py"]["error"])

    def test_spec_change_invalidates_approvals(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_GOOD]})
        p.generate("--auto-approve")
        (p.dir / "spec/core/echo.md").write_text(SPEC_CORE + "- **E-4** (MUST) new rule.\n")
        r = p.friend("generate", check_code=3)
        self.assertIn("spec", r.stderr)
        p.friend("approve", "spec", check_code=0)
        st = p.state()["artifacts"]
        self.assertEqual((st["plan"]["status"], st["tests"]["status"]), ("stale", "stale"))


class Operations(unittest.TestCase):
    def test_reviewer_rejection_regenerates_with_feedback(self):
        p = Project({"planner": [{"output": PLAN_OUT}, {"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [BUILD_GOOD]})
        decisions = iter([("reject", "use py_compile, not compileall"), ("approve", ""), ("approve", "")])
        seen = []

        def reviewer(kind, summary, detail):
            seen.append(kind)
            return next(decisions)
        code = textwrap.dedent(f"""
            import json, os, sys
            sys.path.insert(0, {str(HARNESS)!r})
            os.environ['FRIEND_FAKE_SCENARIO'] = {str(p.scenario)!r}
            from pathlib import Path
            import config, controller, runstate, approvals
            cfg = config.load(Path({str(p.dir)!r}))
            v, _ = controller.preflight(cfg)
            run = runstate.Run.create(cfg.root / '.friend', approvals.spec_hash(cfg), controller.config_hash(cfg.root), v)
            answers = iter({[list(d) for d in [("reject", "use py_compile, not compileall"), ("approve", ""), ("approve", "")]]!r})
            seen = []
            def reviewer(kind, summary, detail):
                seen.append(kind)
                return tuple(next(answers))
            print(json.dumps({{'status': controller.Controller(cfg, run, False, reviewer=reviewer).execute(), 'seen': seen}}))
        """)
        r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, timeout=300)
        out = json.loads(r.stdout.strip().splitlines()[-1])
        self.assertEqual(out, {"status": "passed", "seen": ["plan", "plan", "tests"]})
        planner = [c for c in p.calls() if c["role"] == "planner"]
        self.assertIn("use py_compile, not compileall", planner[1]["prompt"])
        self.assertEqual(json.loads((p.dir / "approvals.json").read_text())["plan"]["by"], "human")


class Hook(unittest.TestCase):
    """The policy hook in isolation (no agent)."""

    def decide(self, tool: str, inp: dict, root: Path) -> int:
        cmd = [sys.executable, str(HARNESS / "policy_hook.py"), "--root", str(root), "--label", "t", "--events", str(root / "ev.jsonl"),
               "--write", "clients/py", "--read", "spec", "--exec", "python3 run.py --target py", "--deny", "friend", "--deny", "tests"]
        return subprocess.run(cmd, input=json.dumps({"tool_name": tool, "tool_input": inp}), capture_output=True, text=True).returncode

    def test_decisions(self):
        root = Path(tempfile.mkdtemp())
        cases = [
            ("Write", {"file_path": "clients/py/a.py"}, 0), ("Write", {"file_path": "tests/x.py"}, 2),
            ("Write", {"file_path": str(root / "clients/py/../../tests/x.py")}, 2),
            ("Read", {"file_path": "spec/a.md"}, 0), ("Read", {"file_path": "tests/x.py"}, 2), ("Grep", {"pattern": "x"}, 2),
            ("Glob", {"pattern": "spec/**/*.md"}, 0), ("Glob", {"pattern": "tests/**"}, 2), ("Glob", {"pattern": "**/*"}, 2),
            ("Bash", {"command": "grep -n x clients/py/friend/client.py"}, 0),       # nested name is not the denied top-level `friend`
            ("Bash", {"command": "friend generate"}, 2),
            ("Bash", {"command": "cat tests/x.py"}, 2), ("Bash", {"command": "python3 run.py --target py --only a"}, 0),
            ("Bash", {"command": "python3 run.py --target py; cat tests/x"}, 2), ("Bash", {"command": "cat ../secret"}, 2),
            ("Bash", {"command": "cat /etc/passwd"}, 2), ("WebFetch", {"url": "http://x"}, 2),
            ("Bash", {"command": "python3 -c print(1)"}, 2), ("Bash", {"command": "node -e 1"}, 2),   # arbitrary code
            ("Bash", {"command": "/usr/bin/python3.12 x.py"}, 2), ("Bash", {"command": "sh -c ls"}, 2),
            ("Bash", {"command": "find clients -exec cat {} +"}, 2),
        ]
        slug = re.sub(r"[^A-Za-z0-9]", "-", str(root.resolve()))
        cases += [("Read", {"file_path": f"/private/tmp/claude-501/{slug}/s1/tasks/b1.output"}, 0),   # own background output
                  ("Read", {"file_path": "/private/tmp/claude-501/-Users-someone-else/s1/tasks/b1.output"}, 2)]
        for tool, inp, want in cases:
            self.assertEqual(self.decide(tool, inp, root), want, f"{tool} {inp}")
        (root / "ev.jsonl").unlink(missing_ok=True)
        self.assertEqual(self.decide("Read", {"file_path": "tests/x"}, root), 2)
        self.assertIn("policy.denied", (root / "ev.jsonl").read_text())

    def test_fails_closed_on_garbage(self):
        root = Path(tempfile.mkdtemp())
        r = subprocess.run([sys.executable, str(HARNESS / "policy_hook.py"), "--root", str(root), "--label", "t", "--events", str(root / "e")],
                           input="not json", capture_output=True, text=True)
        self.assertEqual(r.returncode, 2)


class Resumption(unittest.TestCase):
    def test_interrupt_then_resume_continues_the_same_session(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD], "builder": [{"hang": 30}, BUILD_GOOD]})
        proc = subprocess.Popen(MF + ["--root", str(p.dir), "--json", "generate", "--auto-approve"], env=p.env,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, start_new_session=True)
        deadline = time.time() + 60
        while time.time() < deadline and not any(c["role"] == "builder" for c in p.calls()):
            time.sleep(0.2)
        time.sleep(0.5)
        os.killpg(proc.pid, signal.SIGINT)
        self.assertEqual(proc.wait(30), 130)
        self.assertEqual(p.state()["run"]["status"], "interrupted")
        ev = p.generate()
        self.assertEqual(ev[0]["type"], "run.resumed")
        b = [c for c in p.calls() if c["role"] == "builder"]
        self.assertTrue(b[-1]["resume"] and b[-1]["session"] == b[0]["session"])
        self.assertIn("resumed", b[-1]["prompt"])
        self.assertEqual(ev[-1]["status"], "passed")

    def test_lost_session_starts_a_new_one_with_a_self_contained_prompt(self):
        p = Project({"planner": [{"output": PLAN_OUT}], "tester": [TESTS_GOOD],
                     "builder": [BUILD_BROKEN, {"missing_session": True}, BUILD_GOOD]})
        ev = p.generate("--auto-approve")
        self.assertIn("agent.session_lost", types(ev))
        b = [c for c in p.calls() if c["role"] == "builder"]
        self.assertNotEqual(b[2]["session"], b[0]["session"])
        self.assertFalse(b[2]["resume"])
        self.assertEqual(ev[-1]["status"], "passed")


