"""Self-tests for the generator's control logic, using a scripted fake agent and a toy project.

The toy project is deliberately unrelated to messaging (a line-echo CLI) to show the harness is
spec-agnostic. Every test builds a fresh project in a temp dir and runs the real `friend` CLI.
Run: python3 harness/selftest/test_harness.py [-v] [-k pattern]
"""
